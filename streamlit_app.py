import streamlit as st
import requests

# ====== Page Configuration ======
st.set_page_config(
    page_title='YouTube Video Summarizer',
    page_icon='🎬',
    layout='wide',
    initial_sidebar_state='expanded'
)


# ====== Custom CSS ======
st.markdown(
    '''
    <style>

    .main-title {
        font-size: 42px;
        font-weight: 700;
        text-align: center;
        margin-bottom: 5px;
    }

    .subtitle {
        text-align: center;
        font-size: 18px;
        color: #777;
        margin-bottom: 30px;
    }

    .section-title {
        font-size: 25px;
        font-weight: 650;
        margin-top: 20px;
        margin-bottom: 10px;
    }

    .summary-box {
        padding: 22px;
        border-radius: 14px;
        border: 1px solid #ddd;
        background-color: #fafafa;
        line-height: 1.7;
        font-size: 16px;
    }

    .final-box {
        padding: 25px;
        border-radius: 14px;
        border: 2px solid #ff4b4b;
        background-color: #fff8f8;
        line-height: 1.8;
        font-size: 18px;
    }

    .info-box {
        padding: 15px;
        border-radius: 12px;
        background-color: #f5f7fa;
        border: 1px solid #e1e5ea;
    }

    </style>
    ''',
    unsafe_allow_html=True
)


# ====== Header ======
st.markdown(
    '<div class="main-title">🎬 YouTube Video Summarizer</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="subtitle">Lab 4 — Streamlit GUI + NGROK + FastAPI + Lab 1</div>',
    unsafe_allow_html=True
)


st.markdown(
    '''
    <div class="info-box">
    Enter the NGROK public URL generated by the Kaggle backend,
    then enter a YouTube video URL to generate a Combined Summary
    and a Final Summary.
    </div>
    ''',
    unsafe_allow_html=True
)


st.write('')


# ====== Input Section ======
st.subheader('⚙️ Configuration')


col1, col2 = st.columns(2)


with col1:

    ngrok_url=st.text_input(
        'NGROK Public URL',
        placeholder='https://xxxx.ngrok-free.app'
    )

    api_key=st.text_input(
        'API Key',
        type='password'
    )


with col2:

    youtube_url=st.text_input(
        'YouTube Video URL',
        placeholder='https://www.youtube.com/watch?v=...'
    )

    max_words=st.slider(
        'Transcript Chunk Size (words)',
        200,
        500,
        350,
        50
    )


st.write('')


# ====== Summarize Button ======
if st.button(
    '🚀 Summarize Video',
    type='primary',
    use_container_width=True
):

    if not ngrok_url.strip():

        st.error(
            'Please enter the NGROK public URL.'
        )

        st.stop()


    if not api_key.strip():

        st.error(
            'Please enter the API key.'
        )

        st.stop()


    if not youtube_url.strip():

        st.error(
            'Please enter a YouTube URL.'
        )

        st.stop()


    endpoint=(
        ngrok_url.rstrip('/')
        + '/summarize'
    )


    try:

        with st.spinner(
            '⏳ Processing video on Kaggle... '
            'Please wait until all chunks are summarized.'
        ):

            r=requests.post(
                endpoint,
                headers={
                    'Authorization':
                    f'Bearer {api_key}'
                },
                json={
                    'youtube_url':
                    youtube_url,
                    'max_words':
                    max_words
                },
                timeout=900
            )


        # ====== Error Handling ======
        if r.status_code != 200:

            try:

                detail=r.json().get(
                    'detail',
                    r.text
                )

            except Exception:

                detail=r.text


            st.error(
                f'Backend error ({r.status_code}): {detail}'
            )

            st.stop()


        # ====== Successful Response ======
        result=r.json()


        st.success(
            '✅ Summary generated successfully!'
        )


        # ====== Metrics ======
        c1,c2,c3=st.columns(3)


        c1.metric(
            '🌐 Language',
            result.get(
                'language',
                'N/A'
            )
        )


        c2.metric(
            '📦 Chunks',
            result.get(
                'chunk_count',
                'N/A'
            )
        )


        c3.metric(
            '📝 Transcript Characters',
            result.get(
                'transcript_characters',
                'N/A'
            )
        )


        st.write('')


        # ====== Combined Summary ======
        st.markdown(
            '<div class="section-title">📚 Combined Summary</div>',
            unsafe_allow_html=True
        )


        combined_summary=result.get(
            'combined_summary',
            ''
        )


        st.markdown(
            f'''
            <div class="summary-box">
            {combined_summary}
            </div>
            ''',
            unsafe_allow_html=True
        )


        st.write('')


        # ====== Final Summary ======
        st.markdown(
            '<div class="section-title">✨ Final Summary</div>',
            unsafe_allow_html=True
        )


        final_summary=result.get(
            'summary',
            ''
        )


        st.markdown(
            f'''
            <div class="final-box">
            {final_summary}
            </div>
            ''',
            unsafe_allow_html=True
        )


        st.write('')


        # ====== Technical Details ======
        with st.expander(
            '🔧 Technical Details'
        ):

            st.write(
                'Video ID:',
                result.get(
                    'video_id'
                )
            )

            st.write(
                'API Endpoint:',
                endpoint
            )

            st.write(
                'Chunk Size:',
                max_words
            )

            st.write(
                'Processing Status:',
                '200 OK'
            )


    except requests.exceptions.Timeout:

        st.error(
            '⏰ Request timed out. '
            'Long videos may take several minutes '
            'because every chunk is processed on Kaggle.'
        )


    except requests.exceptions.RequestException as e:

        st.error(
            f'❌ Could not connect to backend: {e}'
        )